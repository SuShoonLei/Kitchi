import type { IngredientCategory } from "@/lib/types";
import { SHELF_LIFE_DAYS } from "@/lib/scan/shelf-life";

export type FoodLabel = {
  name: string;
  category: IngredientCategory;
  unit: string;
  shelfLifeDays: number;
  roughPrice: number;
};

function label(
  name: string,
  category: IngredientCategory,
  unit: string,
  roughPrice: number,
): FoodLabel {
  return { name, category, unit, shelfLifeDays: SHELF_LIFE_DAYS[category], roughPrice };
}

