export function foodLabelNames(): string[] {
  return FOOD_LABELS.map((item) => item.name);
}

export function findFoodLabel(name: string): FoodLabel | undefined {
  const lower = name.toLowerCase();
  return FOOD_LABELS.find((item) => item.name.toLowerCase() === lower);
}
